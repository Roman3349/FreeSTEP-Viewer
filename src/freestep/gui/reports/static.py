"""PDF report of a static exam: the footprint of one pressure frame and, optionally, the photo."""

from __future__ import annotations

import html
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from PySide6.QtGui import QImage

from ...analysis.static import FootPrint, StaticAnalysis, analyze_static
from ...models import Exam, Patient
from ...recording import Recording
from ..exam import region_overlay
from ..i18n import tr
from ..meta import APP_NAME
from ..texts import format_number
from ..widgets import HeatmapView
from .pages import Pages, exam_when, notes_html, paint_header, section

_TABLE = "width='100%' cellspacing='0' cellpadding='2' style='border-collapse: collapse'"
_STRIPE = "#f0f0f0"


@dataclass(frozen=True)
class StaticReportData:
    """Everything the static report shows.

    Attributes:
        patient: The subject.
        exam: The exam.
        post: Its recording (one frame).
        photos: Images to add on their own page (e.g. ``Statica.BMP``) as ``(name, image)``; empty for none.
    """

    patient: Patient
    exam: Exam
    post: Recording
    photos: list[tuple[str, QImage]]


def write_static_report(path: Path, data: StaticReportData) -> None:
    """Write the PDF report of a static exam.

    Contents: subject and exam data, the pressure map with the load quadrants,
    the footprint of each foot (load, front / rear share, contact area, length,
    width, peak and mean value), notes on the methods and, when given, the photos.

    Args:
        path: Output file.
        data: The exam.

    Raises:
        ValueError: The frame has no load.
    """
    acq = data.post.acquisitions[0]
    analysis = analyze_static(acq.pressure[0], data.post.header)
    title = tr("Static report")
    name = data.patient.name
    pages = Pages(path, f"{title} — {name}", f"{name} · {tr('Exam {id}', id=data.exam.id)} · {exam_when(data.exam)}")
    try:
        pages.logo(52)
        pages.text(f"<h1>{html.escape(title)}</h1>")
        paint_header(pages, data.patient, data.exam, [(tr("Platform"), data.post.header.platform)])
        pages.text(section(tr("Pressure map")), keep_with=360)
        pages.widgets([("", _heatmap(data.post, analysis))], 360, 1)
        pages.text(section(tr("Footprint")), keep_with=200)
        pages.text(_footprint_table(analysis))
        notes = [
            tr(
                "Feet split in the gap between them; front and rear half of each foot's length "
                "(toes toward the top of the map). Values in raw sensor units (0–{max}); FreeSTEP "
                "stores no calibration.",
                max=data.post.header.max_value,
            ),
            tr("Quadrants on the map: share of the total load; COP of the whole plate (black) and of the feet."),
            tr("Generated by {app} on {date}.", app=APP_NAME, date=datetime.now().strftime("%Y-%m-%d %H:%M")),
        ]
        pages.text(section(tr("Methods")) + notes_html(notes))
        if data.photos:
            pages.new_page()
            pages.text(section(tr("Photo") if len(data.photos) == 1 else tr("Photos")))
            for caption, image in data.photos:
                pages.image(caption if len(data.photos) > 1 else "", image, 900)
    finally:
        pages.finish()


def _heatmap(post: Recording, analysis: StaticAnalysis) -> HeatmapView:
    """Pressure map of the frame with the load quadrants."""
    acq, header = post.acquisitions[0], post.header
    view = HeatmapView()
    view.smooth = True
    view.set_frame(acq.pressure[0], header.max_value, (float(header.cell_width_mm), float(header.cell_height_mm)))
    shares = dict(
        zip(("left_front_pct", "left_rear_pct", "right_front_pct", "right_rear_pct"), analysis.quadrants, strict=True)
    )
    view.set_regions(*region_overlay(analysis.regions, shares, None))
    return view


def _footprint_table(analysis: StaticAnalysis) -> str:
    """Table of the footprint parameters: left foot, right foot, both feet."""
    feet: list[FootPrint | None] = [analysis.left, analysis.right, analysis.total]
    rows: list[tuple[str, str, list[float | None]]] = [
        (tr("Load"), "%", [f.load_pct if f else None for f in feet]),
        (tr("Front half"), "%", [f.forefoot_pct if f else None for f in feet]),
        (tr("Rear half"), "%", [f.rearfoot_pct if f else None for f in feet]),
        (tr("Contact area"), "cm²", [f.contact_area_cm2 if f else None for f in feet]),
        (tr("Length"), "cm", [f.length_cm if f else None for f in feet]),
        (tr("Width"), "cm", [f.width_cm if f else None for f in feet]),
        (tr("Peak value"), "", [f.peak_value if f else None for f in feet]),
        (tr("Mean value"), "", [f.mean_value if f else None for f in feet]),
    ]
    head = "".join(
        f"<th align='right' width='21%'>{html.escape(c)}</th>"
        for c in (tr("Left foot"), tr("Right foot"), tr("Both feet"))
    )
    lines = [
        f"<tr style='background-color:#dddddd'><th align='left' width='30%'>{html.escape(tr('Parameter'))}</th>"
        f"<th width='7%'></th>{head}</tr>"
    ]
    for number, (label, unit, values) in enumerate(rows):
        cells = "".join(f"<td align='right'>{format_number(v)}</td>" for v in values)
        stripe = f" style='background-color:{_STRIPE}'" if number % 2 else ""
        lines.append(
            f"<tr{stripe}><td>{html.escape(label)}</td><td style='color:#666666'>{html.escape(unit)}</td>{cells}</tr>"
        )
    return f"<table {_TABLE}>{''.join(lines)}</table>"
