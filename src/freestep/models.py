"""Typed views of patients and exams (Italian names mapped to English).

Every model can be built from the MDB row (``from_mdb``) and/or from the INI
section (``from_ini``) and keeps the untouched source values in ``raw``, so
fields that are not mapped yet are still accessible.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import date, time
from enum import Enum

from .convert import to_date, to_float, to_int, to_str, to_time

#: ``TipoEsame`` values (0 is not confirmed yet).
EXAM_TYPES: dict[int, str] = {
    0: "Static",
    1: "Static with photo",  # Statica.dat + Statica.bmp
    2: "Dynamic",  # Dinamica.dat
    3: "Dynamic with video",  # Dinamica.dat + Capture.avi
    4: "Posturography",  # Postura.dat
    6: "Videography",  # VG*.bmp / VG_*.ini
    8: "Podoscanner",  # Scanner.bmp
    11: "Treadmill with video",  # TreadMILL.dat + Capture.avi
}


class Sex(Enum):
    """Sex of a subject (``Sesso``)."""

    MALE = "M"
    FEMALE = "F"


# Values of Sesso: Italian in the database and FreeSTEP's UI, English in some INI files
_SEX_VALUES = {
    "m": Sex.MALE,
    "male": Sex.MALE,
    "maschile": Sex.MALE,
    "maschio": Sex.MALE,
    "f": Sex.FEMALE,
    "female": Sex.FEMALE,
    "femminile": Sex.FEMALE,
    "femmina": Sex.FEMALE,
}


def to_sex(value: object) -> Sex | None:
    """Convert a ``Sesso`` value (``Femminile``, ``Maschile``, ``Female``, ``M``, …) to :class:`Sex`.

    Returns:
        The sex, or ``None`` for an empty or unknown value (the source value stays in ``raw``).
    """
    return _SEX_VALUES.get(to_str(value).strip().casefold())


#: ``FlagCalz`` values.
FOOTWEAR: dict[int, str] = {0: "Barefoot", 1: "Shoes", 2: "Shoes with orthosis"}


@dataclass
class ExportIndex:
    """Summary of the whole export (``Indice.ini``).

    Attributes:
        centre_code: Code of the centre (licence) that created the export
            (``[CENTRO] Codice``).
        created: Export date (``[GENERALI] DataCreazione``).
        patient_count: Number of exported patients (``[GENERALI] Pazienti``).
        exam_count: Number of exported exams (``[GENERALI] Esami``).
        raw: The parsed INI file as ``{section: {key: value}}``.
    """

    centre_code: str
    created: date | None
    patient_count: int | None
    exam_count: int | None
    raw: dict[str, dict[str, str]] = field(default_factory=dict, repr=False)

    @classmethod
    def from_ini(cls, ini: dict[str, dict[str, str]]) -> ExportIndex:
        """Build the index from the parsed ``Indice.ini``.

        Args:
            ini: Result of :func:`freestep.ini.parse_ini`.

        Returns:
            The export summary; missing values are ``None`` / empty.
        """
        centre = ini.get("CENTRO", {})
        general = ini.get("GENERALI", {})
        return cls(
            centre_code=to_str(centre.get("Codice")),
            created=to_date(general.get("DataCreazione")),
            patient_count=to_int(general.get("Pazienti")),
            exam_count=to_int(general.get("Esami")),
            raw=ini,
        )


@dataclass
class Patient:
    """Patient record (MDB table ``Pazienti`` or section ``[Paziente]`` of the INI).

    Attributes:
        id: Patient ID (``ID``).
        name: Full name (``Nominativo``), usually "Surname Name" or "Name Surname".
        birth_date: Date of birth (``DataDiNascita`` in MDB, ``DataNascita`` in INI).
        height_cm: Height in cm (``Altezza``).
        weight_kg: Weight in kg (``Peso``).
        shoe_size_eu: EU shoe size (``Calzatura``).
        shoe_size_us: US shoe size (``ShoeNum``).
        shoe_tag: US sizing system, ``W`` = women, ``M`` = men (``ShoeTag``).
        height_in: Height in inches (``AltezzaINC``).
        weight_lb: Weight in pounds (``PesoLB``).
        units: Preferred units, ``M`` = metric (``Metrica``).
        sex: Sex (``Sesso``), ``None`` when empty (often) or unknown.
        ssid: Unique record ID generated by FreeSTEP (``SSID``).
        note: Free-text note (``Note``).
        raw: All source values (MDB row or INI section), including unmapped ones.
    """

    id: int | None
    name: str
    birth_date: date | None
    height_cm: float | None
    weight_kg: float | None
    shoe_size_eu: float | None
    shoe_size_us: float | None
    shoe_tag: str
    height_in: float | None
    weight_lb: float | None
    units: str
    sex: Sex | None
    ssid: str
    note: str
    raw: dict[str, object] = field(default_factory=dict, repr=False)

    @classmethod
    def from_mdb(cls, row: dict[str, object]) -> Patient:
        """Build a patient from a row of the ``Pazienti`` table.

        Args:
            row: Row as returned by :meth:`freestep.mdb.AccessDatabase.rows`.

        Returns:
            The patient.
        """
        return cls(
            id=to_int(row.get("ID")),
            name=to_str(row.get("Nominativo")),
            birth_date=to_date(row.get("DataDiNascita")),
            height_cm=to_float(row.get("Altezza")),
            weight_kg=to_float(row.get("Peso")),
            shoe_size_eu=to_float(row.get("Calzatura")),
            shoe_size_us=to_float(row.get("ShoeNum")),
            shoe_tag=to_str(row.get("ShoeTAG")),
            height_in=to_float(row.get("AltezzaINC")),
            weight_lb=to_float(row.get("PesoLB")),
            units=to_str(row.get("Metrica")),
            sex=to_sex(row.get("Sesso")),
            ssid=to_str(row.get("SSID")),
            note=to_str(row.get("Note")),
            raw=dict(row),
        )

    @classmethod
    def from_ini(cls, section: dict[str, str]) -> Patient:
        """Build a patient from the ``[Paziente]`` section of ``Paziente(W).ini``.

        Args:
            section: The ``[Paziente]`` section as ``{key: value}``.

        Returns:
            The patient.
        """
        return cls(
            id=to_int(section.get("ID")),
            name=to_str(section.get("Nominativo")),
            birth_date=to_date(section.get("DataNascita")),
            height_cm=to_float(section.get("Altezza")),
            weight_kg=to_float(section.get("Peso")),
            shoe_size_eu=to_float(section.get("Calzatura")),
            shoe_size_us=to_float(section.get("ShoeNum")),
            shoe_tag=to_str(section.get("ShoeTag")),
            height_in=to_float(section.get("AltezzaINC")),
            weight_lb=to_float(section.get("PesoLB")),
            units=to_str(section.get("Metrica")),
            sex=to_sex(section.get("Sesso")),
            ssid=to_str(section.get("SSID")),
            note=to_str(section.get("Note")),
            raw=dict(section),
        )


# Values of Esami.InfoPaziente: "[age][height][weight][shoe][metric][height_in][weight_lb][shoe_tag][shoe_num]"
_INFO_RE = re.compile(r"\[([^\]]*)\]")


@dataclass
class Exam:
    """Exam metadata (MDB table ``Esami`` or ``[Paziente]`` section of a ``.fre``).

    Attributes:
        id: Exam ID (``ID`` in MDB, ``IDEsame`` in INI); also the ``.fre`` file name.
        patient_id: ID of the patient (``IDPaziente`` in MDB, ``ID`` in INI).
        exam_type: Exam type code (``TipoEsame``), see :data:`EXAM_TYPES`.
        footwear: Footwear during the exam (``FlagCalz``), see :data:`FOOTWEAR`.
        exam_date: Date of the exam (``Data`` / ``DataEsame``).
        exam_time: Time of the exam (``Ora`` — minutes only — / ``OraEsame`` with seconds).
        ssid: Unique record ID generated by FreeSTEP (``SSID`` / ``SSIDEsame``).
        note: Free-text note (``NoteEsame`` / ``Nota_Esame``).
        file_name: Name of the exam archive (``NomeFile`` in INI; derived from the ID for MDB).
        age: Patient's age at the exam (MDB only, from ``InfoPaziente``).
        height_cm: Patient's height at the exam (``InfoPaziente`` / ``Altezza_Esame``).
        weight_kg: Patient's weight at the exam (``InfoPaziente`` / ``Peso_Esame``).
        shoe_size_eu: Patient's EU shoe size at the exam (``InfoPaziente`` / ``Calzatura_Esame``).
        raw: All source values (MDB row or INI section), including unmapped ones.
    """

    id: int | None
    patient_id: int | None
    exam_type: int | None
    footwear: int | None
    exam_date: date | None
    exam_time: time | None
    ssid: str
    note: str
    file_name: str
    age: int | None = None
    height_cm: float | None = None
    weight_kg: float | None = None
    shoe_size_eu: float | None = None
    raw: dict[str, object] = field(default_factory=dict, repr=False)

    @property
    def exam_type_name(self) -> str:
        """English name of the exam type, ``"Unknown (N)"`` for codes not in :data:`EXAM_TYPES`."""
        name = EXAM_TYPES.get(self.exam_type) if self.exam_type is not None else None
        return name or f"Unknown ({self.exam_type})"

    @property
    def footwear_name(self) -> str:
        """English name of the footwear, ``"Unknown (N)"`` for codes not in :data:`FOOTWEAR`."""
        name = FOOTWEAR.get(self.footwear) if self.footwear is not None else None
        return name or f"Unknown ({self.footwear})"

    @classmethod
    def from_mdb(cls, row: dict[str, object]) -> Exam:
        """Build an exam from a row of the ``Esami`` table.

        Args:
            row: Row as returned by :meth:`freestep.mdb.AccessDatabase.rows`.

        Returns:
            The exam, including the patient values parsed from ``InfoPaziente``.
        """
        exam_id = to_int(row.get("ID"))
        info = _INFO_RE.findall(to_str(row.get("InfoPaziente")))
        info += [""] * (4 - len(info))
        return cls(
            id=exam_id,
            patient_id=to_int(row.get("IDPaziente")),
            exam_type=to_int(row.get("TipoEsame")),
            footwear=to_int(row.get("FlagCalz")),
            exam_date=to_date(row.get("Data")),
            exam_time=to_time(row.get("Ora")),
            ssid=to_str(row.get("SSID")),
            note=to_str(row.get("NoteEsame")),
            file_name=f"{exam_id:08d}.fre" if exam_id is not None else "",
            age=to_int(info[0]),
            height_cm=to_float(info[1]),
            weight_kg=to_float(info[2]),
            shoe_size_eu=to_float(info[3]),
            raw=dict(row),
        )

    @classmethod
    def from_ini(cls, section: dict[str, str]) -> Exam:
        """Build an exam from the ``[Paziente]`` section of ``Paziente(W).ini``.

        Args:
            section: The ``[Paziente]`` section as ``{key: value}``.

        Returns:
            The exam (``age`` is not stored in the INI files and stays ``None``).
        """
        return cls(
            id=to_int(section.get("IDEsame")),
            patient_id=to_int(section.get("ID")),
            exam_type=to_int(section.get("TipoEsame")),
            footwear=to_int(section.get("FlagCalz")),
            exam_date=to_date(section.get("DataEsame")),
            exam_time=to_time(section.get("OraEsame")),
            ssid=to_str(section.get("SSIDEsame")),
            note=to_str(section.get("Nota_Esame")),
            file_name=to_str(section.get("NomeFile")),
            height_cm=to_float(section.get("Altezza_Esame")),
            weight_kg=to_float(section.get("Peso_Esame")),
            shoe_size_eu=to_float(section.get("Calzatura_Esame")),
            raw=dict(section),
        )


@dataclass
class FilterSettings:
    """Filter applied to the recording (``Filtro.ini``).

    Attributes:
        filter: Filter code (``[FILTRI] Filtro``); 0 means raw (unfiltered) data.
            Other codes are not known yet.
        frequency: Filter frequency (``[FILTRI] Freq``), presumably in Hz.
    """

    filter: int | None
    frequency: float | None

    @property
    def is_raw(self) -> bool:
        """``True`` when the data are not filtered (also when ``Filtro.ini`` is missing)."""
        return not self.filter

    @classmethod
    def from_ini(cls, ini: dict[str, dict[str, str]]) -> FilterSettings:
        """Build the settings from the parsed ``Filtro.ini``.

        Args:
            ini: Result of :func:`freestep.ini.parse_ini`; may be empty.

        Returns:
            The filter settings.
        """
        section = ini.get("FILTRI", {})
        return cls(filter=to_int(section.get("Filtro")), frequency=to_float(section.get("Freq")))
